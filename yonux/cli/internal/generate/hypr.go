package generate

import (
	"encoding/json"
	"fmt"
	"math"
	"os"
	"regexp"
	"strconv"
	"strings"
)

type setting struct {
	key        string
	value      any
	hyprOption bool
}

var settingStart = regexp.MustCompile(`^(\s*)Setting \{\s*$`)
var settingProperty = regexp.MustCompile(`^\s*(key|defaultValue|hyprOption):\s*(.*?)\s*$`)
var settingKey = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*(\.[A-Za-z_][A-Za-z0-9_]*)*$`)

// The QML Setting declarations remain the source of defaults and hyprOption.
// This deliberately reads only their literal properties, not QML expressions or
// singleton lifecycle hooks (which apply cursors and contact the live session).
// An unsupported declaration is an error, never a second fallback defaults table.
func readSettings(path string) ([]setting, error) {
	body, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("read settings schema %s: %w", path, err)
	}
	var settings []setting
	var current *setting
	var indent string
	seen := make(map[string]bool)
	for line := range strings.SplitSeq(string(body), "\n") {
		if match := settingStart.FindStringSubmatch(line); match != nil {
			if current != nil {
				return nil, fmt.Errorf("settings schema %s: nested Setting declaration", path)
			}
			current = &setting{hyprOption: true}
			indent = match[1]
			continue
		}
		if current == nil {
			continue
		}
		if line == indent+"}" || line == indent+"}," {
			if !settingKey.MatchString(current.key) || current.value == nil || seen[current.key] {
				return nil, fmt.Errorf("settings schema %s: invalid, duplicate or nonliteral Setting %q", path, current.key)
			}
			seen[current.key] = true
			settings = append(settings, *current)
			current = nil
			continue
		}
		match := settingProperty.FindStringSubmatch(line)
		if match == nil {
			continue
		}
		switch match[1] {
		case "key":
			err = json.Unmarshal([]byte(match[2]), &current.key)
		case "defaultValue":
			err = json.Unmarshal([]byte(match[2]), &current.value)
			switch current.value.(type) {
			case string, bool, float64:
			default:
				err = fmt.Errorf("expected a string, boolean or number literal")
			}
		case "hyprOption":
			err = json.Unmarshal([]byte(match[2]), &current.hyprOption)
		}
		if err != nil {
			return nil, fmt.Errorf("settings schema %s: %s: %w", path, match[1], err)
		}
	}
	if current != nil || len(settings) == 0 {
		return nil, fmt.Errorf("settings schema %s: missing or incomplete Setting declarations", path)
	}
	return settings, nil
}

func renderHypr(schema, path string) (string, error) {
	settings, err := readSettings(schema)
	if err != nil {
		return "", err
	}
	document, err := readStore(path)
	if err != nil {
		return "", err
	}
	values := make(map[string]any, len(settings))
	tree := &luaTable{}
	for _, s := range settings {
		value := s.value
		if raw, ok := document[s.key]; ok {
			var candidate any
			if err := json.Unmarshal(raw, &candidate); err != nil {
				return "", fmt.Errorf("decode %s: %s: %w", path, s.key, err)
			}
			valid := false
			switch s.value.(type) {
			case string:
				_, valid = candidate.(string)
			case bool:
				_, valid = candidate.(bool)
			case float64:
				_, valid = candidate.(float64)
			}
			if valid {
				value = candidate
			}
		}
		values[s.key] = value
		if s.hyprOption {
			tree.set(strings.Split(s.key, "."), value)
		}
	}

	// These derived values are the same ones used by HyprSettings.toLua.
	layout, layoutOK := values["general.layout"].(string)
	speed, speedOK := values["animations.speed"].(float64)
	theme, themeOK := values["cursor.theme"].(string)
	size, sizeOK := values["cursor.size"].(float64)
	if !layoutOK || !speedOK || !themeOK || !sizeOK {
		return "", fmt.Errorf("settings schema %s: missing layout, animation or cursor settings", schema)
	}
	if layout == "scrolling" {
		inner, inOK := values["general.gaps_in"].(float64)
		outer, outOK := values["general.gaps_out"].(float64)
		if !inOK || !outOK {
			return "", fmt.Errorf("settings schema %s: missing scrolling gaps", schema)
		}
		horizontal := math.Max(0, outer-inner)
		tree.set([]string{"general", "gaps_out"}, &luaTable{fields: []luaField{
			{"top", outer}, {"right", horizontal}, {"bottom", outer}, {"left", horizontal},
		}})
	}
	cursorSize := number(math.Max(16, math.Min(64, math.Floor(size+0.5))))
	var output strings.Builder
	output.WriteString("-- Generated by the yonux settings window from hypr.json. Edit hypr.json, not this file.\nyonux = yonux or {}\nyonux.layout = ")
	output.WriteString(luaQuote(layout))
	output.WriteString("\nyonux.animation_speed = ")
	output.WriteString(number(speed))
	output.WriteString("\n\n")
	for _, env := range []struct{ name, value string }{
		{"XCURSOR_THEME", theme}, {"XCURSOR_SIZE", cursorSize},
		{"HYPRCURSOR_THEME", theme}, {"HYPRCURSOR_SIZE", cursorSize},
	} {
		fmt.Fprintf(&output, "hl.env(%s, %s)\n", luaQuote(env.name), luaQuote(env.value))
	}
	output.WriteString("\nhl.config(")
	writeLiteral(&output, tree, 0)
	output.WriteString(")\nif yonux.apply_animations then yonux.apply_animations() end\n")
	return output.String(), nil
}

type luaField struct {
	key   string
	value any
}

type luaTable struct{ fields []luaField }

func (table *luaTable) set(parts []string, value any) {
	for i := range table.fields {
		field := &table.fields[i]
		if field.key != parts[0] {
			continue
		}
		if len(parts) == 1 {
			field.value = value
		} else {
			field.value.(*luaTable).set(parts[1:], value)
		}
		return
	}
	if len(parts) > 1 {
		child := &luaTable{}
		child.set(parts[1:], value)
		value = child
	}
	table.fields = append(table.fields, luaField{parts[0], value})
}

func writeLiteral(output *strings.Builder, value any, indent int) {
	switch value := value.(type) {
	case string:
		output.WriteString(luaQuote(value))
	case bool:
		output.WriteString(strconv.FormatBool(value))
	case float64:
		output.WriteString(number(value))
	case *luaTable:
		output.WriteString("{\n")
		for _, field := range value.fields {
			output.WriteString(strings.Repeat("    ", indent+1))
			output.WriteString(field.key)
			output.WriteString(" = ")
			writeLiteral(output, field.value, indent+1)
			output.WriteString(",\n")
		}
		output.WriteString(strings.Repeat("    ", indent))
		output.WriteString("}")
	}
}

// JavaScript String(number) uses fixed notation from 1e-6 through 1e21.
func number(value float64) string {
	if value == 0 {
		return "0"
	}
	if math.Abs(value) >= 1e-6 && math.Abs(value) < 1e21 {
		return strconv.FormatFloat(value, 'f', -1, 64)
	}
	text := strconv.FormatFloat(value, 'e', -1, 64)
	text = strings.Replace(text, "e-0", "e-", 1)
	return strings.Replace(text, "e+0", "e+", 1)
}
